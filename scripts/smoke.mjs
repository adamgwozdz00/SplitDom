// Calls a persistence function straight through the Data API, as a user holding their token could.
async function directRpc(name, { token, headers = {}, args = {} }) {
  const response = await fetch(`${SUPABASE_URL}/rest/v1/rpc/${name}`, {
    method: "POST",
    headers: { apikey: SUPABASE_KEY, Authorization: `Bearer ${token}`, "Content-Type": "application/json", ...headers },
    body: JSON.stringify(args),
  });
  return { status: response.status, location: "", body: await response.text() };
}

// The first smoke user's own access token, taken from Supabase Auth directly, not from the app.
async function firstUserToken() {
  const response = await fetch(`${SUPABASE_URL}/auth/v1/token?grant_type=password`, {
    method: "POST",
    headers: { apikey: SUPABASE_KEY, "Content-Type": "application/json" },
    body: JSON.stringify({ email, password }),
  });
  // Fail loudly here, so a sign-in problem does not surface later as a confusing 401 from the gate steps.
  if (!response.ok) throw new Error(`password grant for the first smoke user failed with ${response.status}`);
  const session = await response.json();
  return session.access_token;
}

// A session straight from Supabase Auth (signing the user up first when `signUp` is set), not from the app.
async function authSession(userEmail, { signUp = false } = {}) {
  const path = signUp ? "signup" : "token?grant_type=password";
  const response = await fetch(`${SUPABASE_URL}/auth/v1/${path}`, {
    method: "POST",
    headers: { apikey: SUPABASE_KEY, "Content-Type": "application/json" },
    body: JSON.stringify({ email: userEmail, password }),
  });
  if (!response.ok) throw new Error(`${path} for ${userEmail} failed with ${response.status}`);
  const session = await response.json();
  return { token: session.access_token, userId: session.user.id };
}

